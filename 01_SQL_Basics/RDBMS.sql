-- 1. SQL and MYSQL
-- - SQL is a programming language
-- - MySQL is a software DATABASE syatem that use sql language

-- SQL -- STANDS FOR STRUCTURE QUERY LANGUAGE . 
--     -- IT IS A STANDARD LANGUAGE USED TO CREATE ,READ ,UPDATE AND DEKETE DATA STORED IN RELATIONAL DATABASE .
--     -- IT IS NOT A DATABASE , IT IS A LANGUAGE USE TO COMMUNICATE WITH DATABASE.

-- MYSQL -- MYSQL IS A OPEN SOURCE RELATION DATABASE MANAGMENT SYSTEM (RDBMS) , THAT USE SQL TO MANAGE DATA
         -- IT IS A SOFTWARE SYSTEM NOT A LANGUAGE
         -- VERY POPULAR FOR WEB APPLICATION
         -- USE IN : WEBSITES , DJANGO , PHP, WORLD PRESS ETC.

-- DBMS -- DATA BASE MANAGEMENT SYSTEM
        -- IS A SOFTWARE THAT ALLOWS USE TO STORE , RETRIVE , AND MANAGE DATA EFFICIENTLY
        -- HANDLES - DATA STORAGE , SECURITY , BACKUP ,DATA CONSISTANCY 
        -- CAN BE STORE ,ADDED , DELETED , UPDATED , RETRIVED FROM ONE PLACE 

-- RDBMS -- RELATIONAL DATA BASE MANAGEMENT SYSTEM
         -- IT IS A TYPE OF DBMS THAT STORES DATA IN THE FORM OF TABLE (ROW & COLUMS) AND USE RELATION BETWEEN TABLES.
         -- IT USE SQL LANGUAGE
         -- ENFORCED DATA INTEGRITY USING KEYS 
         -- IT HAVE DOMAIN , INSTANCE , SCHEMA , KEYS THAT IS. NOT IN DBMS
         -- CAN BE STORED ADDED , DELETE ,UPDATE , RETRIVED FROM ONE PLACE




