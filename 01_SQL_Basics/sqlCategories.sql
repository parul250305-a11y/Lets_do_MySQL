-- SQL IS DIVIDED INTO 5 CATAGORIES ACCORDING TO THE COMMANDS/WHAT THEY DO/ ON USE CASE

-- 1. DDL --> STANDS FOR - DATA DEFINATION LANGUAGE
--         --> COMMANDS IN DDL -  ALTER, DROP , TRUNCATE, CREATE 

-- 2. DML --> STANDS FOR - DATA MANIPULATION LANGUAGE
--        --> COMMANDS IN DML - DELETE , INSERT , UPDATE

-- 3. DQL --> STANDS FOR - DATA QUERY LANGUAGE     
--        --> COMMONDS IN DQL - ** SELECT **

-- 4. DCL --> STANDS FOR - DATA CONTROL LANGUAGE
--        --> COMMONDS IN DCL - GRANT , REVOKE         

-- 5. TCL --> STANDS FOR -- TRANSACTION CONTROL LANGUAGE
--        --> COMMONDS IN TCL - ROLL BACK , SAVE POINT , COMMIT , SET TRANSACTION 


